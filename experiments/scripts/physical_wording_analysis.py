"""Analysis for the physical-wording sweep: kappa table, LaTeX, diff summary.

Reads the sweep output (``physical_wording_sweep.py``), recomputes per-model
Cohen's kappa_C against the analyst row with the framework's own
MetricsReport (same abstain / substantive-subset handling as every prior
capture), and emits:

1. ``table3_physical.tex`` — the model x wording table in the exact format
   of the corrected experiment summary's table (bold departures from the
   analyst row, dagger for degenerate model columns, double-dagger for
   abstain cells with perfect substantive agreement).
2. ``diff_summary.md`` — old vs new verdict rows per model and wording.
   Old grid rows come from the v0.17.8-rescored baseline etas
   (``retest_rescored_v0.17.8/<cell>/eta-0.json``); the old thin-frame row
   from ``rendering_gradient_2026-07-02/support-plain-eta.json``. The
   ``intrinsic`` -> ``physical`` column is an axis replacement and is
   labeled as such.

Everything is logged to stdout; nothing existing is modified.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "src"))

from infereval.evaluation import Evaluation  # noqa: E402
from infereval.metrics import MetricsReport  # noqa: E402

MODEL_ORDER = [
    "claude-opus-4.7", "claude-haiku-4.5",
    "deepseek-v4-flash", "deepseek-v4-pro",
    "gemini-2.5-flash", "gemini-2.5-pro",
    "gpt-4.1", "gpt-5.4", "gpt-5.4-mini",
    "mistral-large", "mistral-small",
    "qwen3.8-max", "qwen3.6-flash",
]
WORDINGS = ["original", "physical", "perceptual"]
OLD_WORDING_FOR = {"original": "original", "physical": "intrinsic",
                   "perceptual": "perceptual"}
#: qwen3.8-max replaces the retired qwen3-max (cross-MODEL diff slot).
OLD_MODEL_FOR = {"qwen3.8-max": "qwen3-max"}
ROWS = ["row-0", "row-1", "row-2", "row-3"]
ANALYST = ["good", "good", "good", "bad"]
LETTER = {"good": "G", "bad": "B", "abstain": "A"}

DEFAULT_SWEEP = REPO_ROOT / "experiments/results/stop_sign/physical_wording_2026-10-28"
DEFAULT_OLD_GRID = REPO_ROOT / "experiments/results/stop_sign/retest_rescored_v0.17.8"
DEFAULT_OLD_THIN = (REPO_ROOT /
    "experiments/results/stop_sign/rendering_gradient_2026-07-02/support-plain-eta.json")
DEFAULT_TABLE_OUT = Path(
    "/Users/bradleyallen/Documents/GitHub/stop-sign-note/table3_physical.tex")


def verdict_row(eta_json: Path) -> list[str]:
    data = json.loads(eta_json.read_text())
    v = {it["id"]: it["model_verdict"] for it in data["items"]}
    return [v[r] for r in ROWS]


def kappa_of(eta_json: Path) -> float | None:
    eta = Evaluation.load(eta_json)
    return MetricsReport(eta=eta).cohens_kappa()


def letters(row: list[str], bold_departures: bool) -> str:
    cells = []
    for verdict, ref in zip(row, ANALYST):
        ch = LETTER[verdict]
        if bold_departures and verdict != ref and verdict != "abstain":
            cells.append(rf"\textbf{{{ch}}}")
        else:
            cells.append(ch)
    return r"\," .join(cells).replace(" ", "")


def kappa_cell(kappa: float | None, row: list[str]) -> tuple[str, set[str]]:
    """LaTeX kappa cell + footnote marks used."""
    marks: set[str] = set()
    constant = len({v for v in row}) == 1
    has_abstain = "abstain" in row
    if kappa is None:
        text = r"und."
    else:
        text = f"${kappa:+.3f}$"
    if constant:
        text = (text.rstrip("$") + r"^{\dagger}$") if kappa is not None else (
            r"und.$^{\dagger}$")
        marks.add("dagger")
    elif has_abstain and kappa is not None and kappa == 1.0:
        text = text.rstrip("$") + r"^{\ddagger}$"
        marks.add("ddagger")
    return text, marks


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--sweep-dir", type=Path, default=DEFAULT_SWEEP)
    ap.add_argument("--old-grid", type=Path, default=DEFAULT_OLD_GRID)
    ap.add_argument("--old-thin", type=Path, default=DEFAULT_OLD_THIN)
    ap.add_argument("--table-out", type=Path, default=DEFAULT_TABLE_OUT)
    args = ap.parse_args(argv)

    sweep = args.sweep_dir
    new_rows: dict[tuple[str, str], list[str]] = {}
    new_kappa: dict[tuple[str, str], float | None] = {}
    for m in MODEL_ORDER:
        for w in WORDINGS:
            p = sweep / f"{m}-{w}.json"
            new_rows[(m, w)] = verdict_row(p)
            new_kappa[(m, w)] = kappa_of(p)

    # ---- LaTeX table -------------------------------------------------------
    marks_used: set[str] = set()
    lines = [
        "% Table 3 (physical-wording axis), generated by",
        "% experiments/scripts/physical_wording_analysis.py on branch",
        "% physical-wording. Sweep: physical_wording_2026-10-28 (v0.17.8",
        "% committed-verdict parser; delta(nr) = 'a is not made with",
        "% retroreflective sheeting' in all conditions; analyst row G G G B).",
        r"\begin{table}[ht]",
        r"\centering",
        r"\small",
        r"\setlength{\tabcolsep}{4.5pt}",
        r"\begin{tabular}{l cc cc cc}",
        r"\toprule",
        r"& \multicolumn{2}{c}{\texttt{original}}",
        r"& \multicolumn{2}{c}{\texttt{physical}}",
        r"& \multicolumn{2}{c}{\texttt{perceptual}} \\",
        r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}",
        r"Model & rows 0--3 & $\kappa_C$ & rows 0--3 & $\kappa_C$ "
        r"& rows 0--3 & $\kappa_C$ \\",
        r"\midrule",
        r"Analyst (reference) & G\,G\,G\,B & --- & G\,G\,G\,B & --- "
        r"& G\,G\,G\,B & --- \\",
        r"\midrule",
    ]
    for m in MODEL_ORDER:
        cells = [m]
        for w in WORDINGS:
            row = new_rows[(m, w)]
            k_text, marks = kappa_cell(new_kappa[(m, w)], row)
            marks_used |= marks
            cells.append(letters(row, bold_departures=True))
            cells.append(k_text)
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    caption = [
        r"\caption{Verdict rows ($E_M$ on items row-0\,\ldots\,row-3; "
        r"G = \textit{good}, B = \textit{bad}, A = \textit{abstain}) and "
        r"Cohen's $\kappa_C$ against the analyst row, per $\delta(ra)$ "
        r"wording, under the physical-wording axis "
        r"($\delta(nr)$ = ``$a$ is not made with retroreflective "
        r"sheeting'' in all conditions; capture of 28 October 2026, "
        r"framework v0.17.8). Bold marks departures from the analyst row.",
    ]
    if "dagger" in marks_used:
        caption.append(
            r"$^{\dagger}$Degenerate substantive subset: the model's column "
            r"is constant, so $\kappa_C$ carries no agreement signal beyond "
            r"the raw row shown.")
    if "ddagger" in marks_used:
        caption.append(
            r"$^{\ddagger}$Abstain present; substantive agreement is perfect "
            r"on the remaining items.")
    lines.append(" ".join(caption) + "}")
    lines += [r"\label{tab:models-physical}", r"\end{table}", ""]
    args.table_out.write_text("\n".join(lines))
    print(f"wrote {args.table_out}")

    # ---- Diff summary ------------------------------------------------------
    diff_lines = [
        "# Physical-wording sweep: old vs new verdict rows",
        "",
        f"New: `{sweep.name}` (v0.17.8 parser, "
        "delta(nr) = 'retroreflective sheeting').",
        "Old grid: `retest_rescored_v0.17.8` baselines (v0.17.8 parser, "
        "delta(nr) = 'reflective material').",
        "The `physical` column replaces the old `intrinsic` wording — that "
        "diff is an axis replacement, not a rerun of the same cell.",
        "",
        "| Model | wording | old row | new row | changed items |",
        "|---|---|---|---|---|",
    ]
    n_changed = 0
    for m in MODEL_ORDER:
        old_m = OLD_MODEL_FOR.get(m, m)
        for w in WORDINGS:
            old_w = OLD_WORDING_FOR[w]
            old_eta = args.old_grid / f"{old_m}-{old_w}" / "eta-0.json"
            old = verdict_row(old_eta)
            new = new_rows[(m, w)]
            changed = [ROWS[i] for i in range(4) if old[i] != new[i]]
            n_changed += bool(changed)
            label = w if w != "physical" else "intrinsic->physical"
            model_label = m if old_m == m else f"{old_m}->{m}"
            diff_lines.append(
                "| {} | {} | {} | {} | {} |".format(
                    model_label, label,
                    " ".join(LETTER[v] for v in old),
                    " ".join(LETTER[v] for v in new),
                    ", ".join(changed) if changed else "—",
                )
            )
    # Thin-frame addendum (gpt-4.1 only; old exists for original wording only)
    diff_lines += ["", "## Thin default-frame (GPT-4.1, July gradient config)", ""]
    diff_lines += ["| wording | old row | new row | note |", "|---|---|---|---|"]
    old_thin = verdict_row(args.old_thin)
    for w in WORDINGS:
        new = verdict_row(sweep / f"thin-gpt-4.1-{w}.json")
        if w == "original":
            changed = [ROWS[i] for i in range(4) if old_thin[i] != new[i]]
            note = ", ".join(changed) if changed else "no change"
            old_s = " ".join(LETTER[v] for v in old_thin)
        else:
            note = "new condition (no July counterpart)"
            old_s = "—"
        diff_lines.append("| {} | {} | {} | {} |".format(
            w, old_s, " ".join(LETTER[v] for v in new), note))
    diff_path = sweep / "diff_summary.md"
    diff_path.write_text("\n".join(diff_lines) + "\n")
    print(f"wrote {diff_path} ({n_changed} grid cells with changes)")
    print("\n".join(diff_lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
